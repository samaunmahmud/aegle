import type { StudyStatus, Urgency, WorklistState } from "../api/types";

export function UrgencyBadge({ urgency }: { urgency: Urgency | null }) {
  if (!urgency) return <span className="badge badge-neutral">Pending</span>;
  const cls = { CRITICAL: "badge-critical", URGENT: "badge-urgent", ROUTINE: "badge-routine" }[urgency];
  return <span className={`badge ${cls}`}>{urgency}</span>;
}

/**
 * Triage priority as reporting systems show it: a fixed-width code (P1–P3) plus the word,
 * so it reads the same in colour and in greyscale (or to someone colour-blind).
 */
export function PriorityTag({ urgency }: { urgency: Urgency | null }) {
  if (!urgency) return <span className="ptag ptag-none">P–</span>;
  const code = { CRITICAL: "P1", URGENT: "P2", ROUTINE: "P3" }[urgency];
  const word = { CRITICAL: "Critical", URGENT: "Urgent", ROUTINE: "Routine" }[urgency];
  return (
    <span className={`ptag ptag-${urgency}`}>
      <b>{code}</b> {word}
    </span>
  );
}

/** Marks machine-generated content, so it is never mistaken for a clinician's finding. */
export function AiTag() {
  return (
    <span className="ai-tag" title="Generated by an AI model: a suggestion until a clinician signs a review">
      AI
    </span>
  );
}

export function StateBadge({ state }: { state: WorklistState }) {
  const cls = { OPEN: "badge-neutral", IN_REVIEW: "badge-progress", DONE: "badge-done" }[state];
  const label = { OPEN: "Unread", IN_REVIEW: "Reading", DONE: "Reported" }[state];
  return <span className={`badge ${cls}`}>{label}</span>;
}

export function StatusBadge({ status }: { status: StudyStatus }) {
  const cls: Record<StudyStatus, string> = {
    RECEIVED: "badge-neutral",
    QUEUED: "badge-neutral",
    ANALYZING: "badge-progress",
    READY: "badge-routine",
    REVIEWED: "badge-done",
    FAILED: "badge-critical",
  };
  const label: Record<StudyStatus, string> = {
    RECEIVED: "Received",
    QUEUED: "Queued for AI",
    ANALYZING: "AI analysing",
    READY: "Ready to report",
    REVIEWED: "Reviewed",
    FAILED: "AI failed",
  };
  return <span className={`badge ${cls[status]}`}>{label[status]}</span>;
}
